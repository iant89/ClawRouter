/**
 * SEC-014: the authorization matrix. Every route × every kind of caller, as a
 * committed, machine-readable file (`matrix.json`) and a readable table
 * (`docs/security/authorization-matrix.md`). Both are generated from the router
 * and the built-in roles by `bun run security:matrix`; the test suite fails when
 * the committed files differ from the code, so any change of who may call what
 * shows up as a reviewed diff, and then checks every cell over HTTP.
 */
import { BUILT_IN_ROLE_PERMISSIONS } from '@clawrouter/authorization';
import type { Permission } from '@clawrouter/shared';

export const PRINCIPALS = ['anonymous', 'apiKey', 'mcpKey', 'admin', 'operator', 'viewer', 'noRole'] as const;
export type Principal = (typeof PRINCIPALS)[number];

export const PRINCIPAL_LABELS: Record<Principal, string> = {
  anonymous: 'Anonymous',
  apiKey: 'API key',
  mcpKey: 'API key with MCP access',
  admin: 'Administrator',
  operator: 'Operator',
  viewer: 'Viewer',
  noRole: 'Signed in, no role',
};

/** Console principals and the built-in role each holds (none for noRole). */
export const CONSOLE_ROLES = { admin: 'ADMIN', operator: 'OPERATOR', viewer: 'VIEWER', noRole: null } as const;

export type Cell = 'Y' | 'N';

export interface MatrixRoute {
  method: string;
  path: string;
  access: string;
  allowed: Record<Principal, Cell>;
}

export interface Matrix {
  description: string;
  principals: Principal[];
  routes: MatrixRoute[];
}

/** Who passes the router's access check for a route's declared access. */
export function cellsFor(access: string): Record<Principal, Cell> {
  const yes = (b: boolean): Cell => (b ? 'Y' : 'N');
  const signedIn = (p: Principal) => p in CONSOLE_ROLES;
  const out = {} as Record<Principal, Cell>;
  for (const p of PRINCIPALS) {
    if (access === 'public') out[p] = 'Y';
    else if (access === 'api_key') out[p] = yes(p === 'apiKey' || p === 'mcpKey');
    else if (access === 'mcp') out[p] = yes(p === 'mcpKey');
    else if (access === 'authenticated') out[p] = yes(signedIn(p));
    else {
      const role = signedIn(p) ? CONSOLE_ROLES[p as keyof typeof CONSOLE_ROLES] : null;
      out[p] = yes(role !== null && BUILT_IN_ROLE_PERMISSIONS[role].includes(access as Permission));
    }
  }
  return out;
}

export function buildMatrix(routes: { method: string; pattern: string; access: string }[]): Matrix {
  return {
    description: 'ClawRouter authorization matrix (SEC-014). Generated by `bun run security:matrix`; do not edit by hand. Y = passes the route\'s access check. MCP needs the mcpEnabled setting as well (otherwise /v1/mcp is a 404 for everyone).',
    principals: [...PRINCIPALS],
    routes: routes
      .map((r) => ({ method: r.method, path: r.pattern, access: r.access, allowed: cellsFor(r.access) }))
      .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method)),
  };
}

export const renderJson = (m: Matrix) => `${JSON.stringify(m, null, 2)}\n`;

/** Area of a route, for the readable table: `/api/<area>` or `/v1`. */
function area(path: string) {
  const parts = path.split('/').filter(Boolean);
  return parts[0] === 'v1' ? (parts[1] === 'mcp' ? 'mcp' : 'gateway (/v1)') : parts[1] === 'me' ? 'me' : (parts[1] ?? '');
}

export function renderMarkdown(m: Matrix) {
  const head = `| Route | Access | ${m.principals.map((p) => PRINCIPAL_LABELS[p]).join(' | ')} |`;
  const rule = `|---|---|${m.principals.map(() => ':-:').join('|')}|`;
  const groups = new Map<string, MatrixRoute[]>();
  for (const r of m.routes) groups.set(area(r.path), [...(groups.get(area(r.path)) ?? []), r]);
  const sections = [...groups.entries()].map(([name, rs]) => [
    `### ${name}`, '', head, rule,
    ...rs.map((r) => `| \`${r.method} ${r.path}\` | \`${r.access}\` | ${m.principals.map((p) => (r.allowed[p] === 'Y' ? 'Y' : '·')).join(' | ')} |`),
    '',
  ].join('\n'));
  return [
    '# Authorization matrix',
    '',
    '<!-- Generated by `bun run security:matrix` from the router and the built-in roles. Do not edit by hand. -->',
    '',
    'Who passes each route\'s access check (SEC-014). **Y** allowed, **·** refused',
    '(401 without the right kind of credential, 403 without the permission). Custom',
    'roles get exactly the permissions they are given. A route that passes the check',
    'may still refuse for its own reasons: ownership (own keys, own sessions), no',
    'escalation (roles and users), a feature switched off (the playground, MCP) or a',
    'temporary password / missing two-factor setup.',
    '',
    'The machine-readable copy is `tests/security/authorization/matrix.json`;',
    '`tests/security/authorization/matrix.test.ts` fails when either differs from the',
    'code, then calls every route as every principal.',
    '',
    `${m.routes.length} routes.`,
    '',
    ...sections,
  ].join('\n');
}
